use cccp::profile::assemble_gost_specs;
use std::fs;
use tempfile::tempdir;

#[test]
fn test_assemble_rules_cascade_and_custom_rules() {
    let dir = tempdir().expect("tempdir");
    let p = dir.path();

    fs::create_dir_all(p.join(".gost")).unwrap();
    fs::write(p.join("GOSTVER"), "GOST_VERSION=\"3.0.0\"\nGOST_PROFILE_URL=\"https://lilya.2lp.in/profile.md\"\n").unwrap();
    fs::write(p.join("VERSION"), "1.0.0\n").unwrap();

    // Create a local custom-rules.toml
    let custom_rules = r#"
[rules.LOCAL-001]
name = "LOCAL-CUSTOM-RULE"
severity = "error"
scope = "local"
description = "Local custom rule for repository"
script = "return true"
"#;
    fs::write(p.join("custom-rules.toml"), custom_rules).unwrap();

    let res = assemble_gost_specs(p);
    assert!(res.is_ok(), "assemble_gost_specs should succeed: {:?}", res.err());

    let compiled_rules_path = p.join(".gost").join("rules.toml");
    assert!(
        compiled_rules_path.is_file(),
        ".gost/rules.toml should be generated by assemble"
    );

    let compiled_content = fs::read_to_string(&compiled_rules_path).unwrap();
    assert!(
        compiled_content.contains("[rules.LOCAL-001]"),
        ".gost/rules.toml must include LOCAL-001 from custom-rules.toml"
    );

    // Verify .gost/GOST.md has no imperialist terms
    let gost_md_path = p.join(".gost").join("GOST.md");
    if gost_md_path.is_file() {
        let gost_md = fs::read_to_string(&gost_md_path).unwrap();
        assert!(
            !gost_md.to_lowercase().contains("soberan"),
            ".gost/GOST.md must not contain prohibited imperialist terms"
        );
    }
}
