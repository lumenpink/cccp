use cccp::profile::assemble_gost_specs;
use std::fs;
use tempfile::tempdir;

#[test]
fn test_assemble_rules_cascade_and_custom_rules() {
    let dir = tempdir().expect("tempdir");
    let p = dir.path();

    fs::create_dir_all(p.join(".gost")).unwrap();
    fs::write(
        p.join("GOSTVER"),
        "GOST_VERSION=\"3.0.0\"\nGOST_PROFILE_URL=\"https://lilya.2lp.in/profile.md\"\n",
    )
    .unwrap();
    fs::write(p.join("VERSION"), "1.0.0\n").unwrap();

    // Create a local custom-rules.toml
    let custom_rules = r#"
[rules.LOCAL-001]
name = "LOCAL-CUSTOM-RULE"
severity = "error"
scope = "local"
description = "Local custom rule for repository"
script = "return true"
"#;
    fs::write(p.join("custom-rules.toml"), custom_rules).unwrap();

    let res = assemble_gost_specs(p);
    assert!(
        res.is_ok(),
        "assemble_gost_specs should succeed: {:?}",
        res.err()
    );

    let compiled_rules_path = p.join(".gost").join("rules.toml");
    assert!(
        compiled_rules_path.is_file(),
        ".gost/rules.toml should be generated by assemble"
    );

    let compiled_content = fs::read_to_string(&compiled_rules_path).unwrap();
    assert!(
        compiled_content.contains("[rules.LOCAL-001]"),
        ".gost/rules.toml must include LOCAL-001 from custom-rules.toml"
    );

    // Verify .gost/GOST.md has no imperialist terms
    let gost_md_path = p.join(".gost").join("GOST.md");
    if gost_md_path.is_file() {
        let gost_md = fs::read_to_string(&gost_md_path).unwrap();
        assert!(
            !gost_md.to_lowercase().contains("soberan"),
            ".gost/GOST.md must not contain prohibited imperialist terms"
        );
    }

    // Mutation Test: ensure assemble handles repositories without custom-rules.toml
    let dir_no_custom = tempdir().expect("tempdir");
    let p2 = dir_no_custom.path();
    fs::create_dir_all(p2.join(".gost")).unwrap();
    fs::write(
        p2.join("GOSTVER"),
        "GOST_VERSION=\"3.0.0\"\nGOST_PROFILE_URL=\"https://lilya.2lp.in/profile.md\"\n",
    )
    .unwrap();
    fs::write(p2.join("VERSION"), "1.0.0\n").unwrap();

    let res2 = assemble_gost_specs(p2);
    assert!(res2.is_ok());
    let compiled_no_custom = p2.join(".gost").join("rules.toml");
    assert!(compiled_no_custom.is_file());
    let content_no_custom = fs::read_to_string(&compiled_no_custom).unwrap();
    assert!(!content_no_custom.contains("[rules.LOCAL-001]"));
}

#[test]
fn test_assemble_purges_prohibited_terms_from_custom_md() {
    let dir = tempdir().expect("tempdir");
    let p = dir.path();
    fs::create_dir_all(p.join(".gost")).unwrap();
    fs::write(
        p.join("GOSTVER"),
        "GOST_VERSION=\"3.0.0\"\nGOST_PROFILE_URL=\"https://lilya.2lp.in/profile.md\"\n",
    )
    .unwrap();
    fs::write(p.join("VERSION"), "1.0.0\n").unwrap();
    fs::write(
        p.join("CUSTOM.md"),
        "# Custom Spec\nForja soberana e espelhamento soberano.\n",
    )
    .unwrap();

    let res = assemble_gost_specs(p);
    assert!(res.is_ok(), "assemble must succeed");
    let gost_md = fs::read_to_string(p.join(".gost/GOST.md")).expect("GOST.md must exist");
    assert!(
        !gost_md.to_lowercase().contains("soberan"),
        "assemble_gost_specs must purge prohibited terms like 'soberan'"
    );
}

#[test]
fn test_get_rules_candidate_urls_deterministic() {
    use cccp::profile::{fetch_rules_from_urls, get_rules_candidate_urls};

    let candidates = get_rules_candidate_urls("https://example.org/rules/1.2.0/RULES.md");
    assert_eq!(
        candidates,
        vec!["https://example.org/rules/1.2.0/RULES.toml".to_string()]
    );

    // Mutation Test: ensure pure failures return None deterministically
    let only_invalid = vec!["https://127.0.0.1:9/invalid-rules.toml".to_string()];
    assert!(
        fetch_rules_from_urls(&only_invalid).is_none(),
        "Must return None when all URLs fail"
    );
    assert!(
        fetch_rules_from_urls(&[]).is_none(),
        "Must return None for empty URL list"
    );
}

#[test]
fn test_assemble_rules_injects_hierarchical_tier() {
    let dir = tempdir().expect("tempdir");
    let p = dir.path();

    fs::create_dir_all(p.join(".rules")).unwrap();
    fs::write(
        p.join(".rules").join("profile.toml"),
        "url = \"https://lilya.2lp.in\"\nversion = \"2.1.0\"\n",
    )
    .unwrap();

    // Create a local custom-rules.toml without tier
    let custom_rules = r#"
[rules.LOCAL-TIER-TEST]
name = "LOCAL-TIER-TEST"
severity = "error"
scope = "local"
description = "Local rule without explicit tier"
script = "return true"
"#;
    fs::write(p.join("custom-rules.toml"), custom_rules).unwrap();

    let res = assemble_gost_specs(p);
    assert!(res.is_ok(), "assemble must succeed");

    let rules_toml =
        fs::read_to_string(p.join(".rules/RULES.toml")).expect("RULES.toml must exist");
    let parsed: toml::Value =
        toml::from_str(&rules_toml).expect("Must parse RULES.toml as valid TOML");
    let local_rule = parsed
        .get("rules")
        .and_then(|r| r.get("LOCAL-TIER-TEST"))
        .expect("LOCAL-TIER-TEST must be present in compiled rules");

    let tier = local_rule
        .get("tier")
        .and_then(|t| t.as_integer())
        .expect("LOCAL-TIER-TEST must have an injected tier");

    assert_eq!(
        tier, 99,
        "Local custom rules without explicit tier must be injected with tier 99"
    );
}

#[test]
fn test_mutation_assemble_preserves_explicit_tier() {
    let dir = tempdir().expect("tempdir");
    let p = dir.path();

    fs::create_dir_all(p.join(".rules")).unwrap();
    fs::write(
        p.join(".rules").join("profile.toml"),
        "url = \"https://lilya.2lp.in\"\nversion = \"2.1.0\"\n",
    )
    .unwrap();

    // Create a local custom-rules.toml with explicit tier
    let custom_rules = r#"
[rules.LOCAL-EXPLICIT-TIER]
tier = 5
name = "LOCAL-EXPLICIT"
severity = "error"
scope = "local"
description = "Local rule with explicit tier"
script = "return true"
"#;
    fs::write(p.join("custom-rules.toml"), custom_rules).unwrap();

    let res = assemble_gost_specs(p);
    assert!(res.is_ok(), "assemble must succeed");

    let rules_toml =
        fs::read_to_string(p.join(".rules/RULES.toml")).expect("RULES.toml must exist");
    let parsed: toml::Value =
        toml::from_str(&rules_toml).expect("Must parse RULES.toml as valid TOML");
    let local_rule = parsed
        .get("rules")
        .and_then(|r| r.get("LOCAL-EXPLICIT-TIER"))
        .expect("LOCAL-EXPLICIT-TIER must be present in compiled rules");

    let tier = local_rule
        .get("tier")
        .and_then(|t| t.as_integer())
        .expect("LOCAL-EXPLICIT-TIER must preserve tier");

    assert_eq!(
        tier, 5,
        "Explicit tier in rule definition must be preserved by assemble"
    );
}
